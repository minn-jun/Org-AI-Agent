def build() -> int:
    n = 0
    for name, tier, title, source_type, date, project, status, summary, url, body in DOCS:
        path = OUT / tier / f"{name}.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        front = [
            "---",
            f"memory_tier: {tier}",
            f"source_type: {source_type}",
            f"project: {project}",
            f"title: {title}",
            f"date: {date}",
            "permission_scope: project_team",
            f"status: {status}",
            f"summary: {summary}",
        ]
        if url:
            front.append(f"source_url: {url}")
        front.append("---")
        path.write_text("\n".join(front) + f"\n# {title}\n\n{body}\n", encoding="utf-8")
        n += 1
    counts = {t: len(list((OUT / t).glob("*.md"))) for t in ("stm", "mtm")}
    print(f"작성 {n}건 -> {OUT}  {counts}")
    return 0


if __name__ == "__main__":
    raise SystemExit(build())
