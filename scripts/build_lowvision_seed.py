# --------------------------------------------------------------------------- 유틸

def md(meta: dict, body: str) -> str:
    lines = ["---"]
    for k, v in meta.items():
        lines.append(f"{k}: {v}")
    lines.append("---")
    lines.append("")
    return "\n".join(lines) + body.strip() + "\n"


def meta(source_type: str, title: str, date: str, summary: str,
         project: str = PROJECT, tier: str = "mtm",
         scope: str = "project_team", status: str = "draft") -> dict:
    return {
        "memory_tier": tier,
        "source_type": source_type,
        "project": project,
        "title": title,
        "date": date,
        "permission_scope": scope,
        "status": status,
        "summary": summary,
    }


FILES: dict[str, str | dict] = {}


def mtm(name: str, source_type: str, title: str, date: str, summary: str,
        body: str, *, project: str = PROJECT, status: str = "draft",
        scope: str = "project_team") -> None:
    FILES[f"mtm/{name}.md"] = md(
        meta(source_type, title, date, summary, project, "mtm", scope, status), body
    )


def stm_md(name: str, source_type: str, title: str, date: str, summary: str,
           body: str, *, project: str = PROJECT, status: str = "active",
           scope: str = "project_team") -> None:
    FILES[f"stm/{name}.md"] = md(
        meta(source_type, title, date, summary, project, "stm", scope, status), body
    )


def stm_json(name: str, payload: dict) -> None:
    FILES[f"stm/{name}.json"] = json.dumps(payload, ensure_ascii=False, indent=2) + "\n"


